// Compile the JSON schemas in this directory into standalone validator code at
// build time. Ajv normally compiles schemas at runtime with `new Function`,
// which Cockpit's Content-Security-Policy (no 'unsafe-eval') forbids; the
// generated module contains plain functions and needs no eval.

import fs from 'node:fs';
import path from 'node:path';

import Ajv from 'ajv';
import standaloneCode from 'ajv/dist/standalone/index.js';

const SCHEMAS = ['store', 'index', 'index-app', 'meta', 'compose'];

export function generateValidators(outFile) {
    const ajv = new Ajv({
        code: { source: true, esm: true },
        strict: true,
        // count string length in UTF-16 units; otherwise the generated code
        // require()s a runtime helper (ajv prints a deprecation note for this)
        unicode: false,
    });
    const exports = {};
    for (const name of SCHEMAS) {
        const schema = JSON.parse(fs.readFileSync(path.join(import.meta.dirname, `${name}.schema.json`), 'utf8'));
        ajv.addSchema(schema);
        exports['validate_' + name.replace('-', '_')] = name;
    }
    const code = '// Generated by schemas/generate.js. Do not edit.\n' + standaloneCode(ajv, exports);
    if (/\b(?:require|eval)\s*\(|new Function/.test(code))
        throw new Error('generated validator code needs require() or eval');
    fs.mkdirSync(path.dirname(outFile), { recursive: true });
    if (!fs.existsSync(outFile) || fs.readFileSync(outFile, 'utf8') !== code)
        fs.writeFileSync(outFile, code);
}
